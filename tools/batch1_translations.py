import os

def escape_xml(s):
    s = s.replace('&', '&amp;')
    s = s.replace("'", "\\'")
    s = s.replace('"', '\\"')
    return s

def make_xml(d):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for k, v in d.items():
        val = escape_xml(v)
        lines.append(f'    <string name="{k}">{val}</string>')
    lines.append('</resources>\n')
    return '\n'.join(lines)

def write_translation(lang_code, d):
    folder = f"app/src/main/res/values-{lang_code}"
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "strings.xml")
    with open(path, "w", encoding="utf-8") as f:
        f.write(make_xml(d))
    print(f"Written {path}")

