def escape_xml(s):
    # Escape special xml characters and single quotes
    s = s.replace("&", "&amp;")
    s = s.replace("<", "&lt;")
    s = s.replace(">", "&gt;")
    s = s.replace("'", "\\'")
    s = s.replace('"', '\\"')
    return s

def build_xml(strings_dict):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for k, v in strings_dict.items():
        escaped_v = escape_xml(v)
        lines.append(f'    <string name="{k}">{escaped_v}</string>')
    lines.append('</resources>\n')
    return "\n".join(lines)

def main():
    base_dir = "app/src/main/res"
    count = 0
    for lang, s_map in TRANSLATIONS.items():
        lang_dir = os.path.join(base_dir, f"values-{lang}")
        os.makedirs(lang_dir, exist_ok=True)
        xml_path = os.path.join(lang_dir, "strings.xml")
        
        # Merge with english fallback if any key missing
        full_map = {}
        for k in ENGLISH_STRINGS.keys():
            full_map[k] = s_map.get(k, ENGLISH_STRINGS[k])
            
        xml_content = build_xml(full_map)
        with open(xml_path, "w", encoding="utf-8") as f:
            f.write(xml_content)
        count += 1
        print(f"Written {xml_path}")

    print(f"Total localized languages generated: {count}")

if __name__ == "__main__":
    main()
